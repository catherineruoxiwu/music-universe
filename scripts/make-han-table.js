// Writes src/enrich/hanTable.ts: every Chinese character whose simplified form is a different
// single character, according to the "Hant-Hans" transform of the ICU library that ships with macOS.
//
// Run on a Mac:  osascript -l JavaScript scripts/make-han-table.js
ObjC.import('Foundation');

function simplify(text) {
  return ObjC.unwrap($.NSString.alloc.initWithString(text).stringByApplyingTransformReverse('Hant-Hans', false));
}

function run() {
  let traditional = '';
  let simplified = '';
  // CJK Unified Ideographs, Extension A, and Compatibility Ideographs.
  for (const [low, high] of [[0x3400, 0x4dbf], [0x4e00, 0x9fff], [0xf900, 0xfaff]]) {
    for (let code = low; code <= high; code++) {
      const character = String.fromCharCode(code);
      const result = simplify(character);
      if (result !== character && result.length === 1) {
        traditional += character;
        simplified += result;
      }
    }
  }
  const source =
    '// Generated by scripts/make-han-table.js from the ICU "Hant-Hans" transform. Do not edit.\n' +
    '\n' +
    '/** Chinese characters that have a different simplified form, and that form at the same position in SIMPLIFIED. */\n' +
    `export const TRADITIONAL = '${traditional}';\n` +
    `export const SIMPLIFIED = '${simplified}';\n`;
  $.NSString.alloc.initWithString(source).writeToFileAtomicallyEncodingError('src/enrich/hanTable.ts', true, $.NSUTF8StringEncoding, null);
  return `${traditional.length} characters`;
}
